"""
Load data_updated.csv into MySQL table employment_permit_2026.

Safe to re-run: rows are matched on the UNIQUE company_name, so existing
companies are updated and new ones inserted. `id` is AUTO_INCREMENT and is
generated by MySQL, so it is not in the CSV or in this script.

Setup:
    pip install pandas sqlalchemy pymysql python-dotenv

.env file (add it to .gitignore):
    DB_USER=root
    DB_PASSWORD=yourpassword
    DB_HOST=localhost
    DB_PORT=3306
    DB_NAME=employment_permits
"""

import os

import pandas as pd
from dotenv import load_dotenv
from sqlalchemy import create_engine, text

CSV_PATH = "data_updated.csv"
TABLE = "employment_permit_2026"

# Left side = column names in YOUR csv, right side = table column names.
# Edit the left side if your CSV uses different names.
COLUMN_MAP = {
    "employer_name": "company_name",
    "permits_total": "permit_count",
    "sector": "sector",
    "size": "size_of_company",
}
FINAL_COLUMNS = ["company_name", "permit_count", "sector", "size_of_company"]


def get_engine():
    load_dotenv()
    url = (
        f"mysql+pymysql://{os.getenv('DB_USER')}:{os.getenv('DB_PASSWORD')}"
        f"@{os.getenv('DB_HOST', 'localhost')}:{os.getenv('DB_PORT', '3306')}"
        f"/{os.getenv('DB_NAME')}?charset=utf8mb4"
    )
    return create_engine(url)


def load_and_clean(path):
    df = pd.read_csv("C:/Users/SUCHETA PV/Desktop/web/Irish-Employment-Permit-Explorer/data/raw/data_updated.csv")
    print("CSV columns found:", df.columns.tolist())

    missing = [c for c in COLUMN_MAP if c not in df.columns]
    if missing:
        raise KeyError(
            f"Columns {missing} not found in CSV. Edit COLUMN_MAP at the top of this script."
        )

    df = df.rename(columns=COLUMN_MAP)[FINAL_COLUMNS]

    # company_name: trim, drop blanks
    df["company_name"] = df["company_name"].astype("string").str.strip()
    df = df[df["company_name"].notna() & (df["company_name"] != "")]

    # permit_count: numeric, non-negative integer
    df["permit_count"] = pd.to_numeric(df["permit_count"], errors="coerce")
    bad = df["permit_count"].isna() | (df["permit_count"] < 0)
    if bad.any():
        print(f"Dropping {bad.sum()} rows with invalid permit_count")
        df = df[~bad]
    df["permit_count"] = df["permit_count"].astype(int)

    # sector / size: unknown handling
    for col in ["sector", "size_of_company"]:
        df[col] = df[col].astype("string").str.strip()
        df[col] = df[col].replace("", pd.NA).fillna("Unknown")

    # company_name is UNIQUE in MySQL: combine duplicates in the CSV
    dupes = df["company_name"].duplicated().sum()
    if dupes:
        print(f"Combining {dupes} duplicate company names (summing permit_count)")
        df = (
            df.groupby("company_name", as_index=False)
            .agg(
                permit_count=("permit_count", "sum"),
                sector=("sector", "first"),
                size_of_company=("size_of_company", "first"),
            )
        )

    # convert pandas NA to plain Python values for the DB driver
    return df.astype(object).where(df.notna(), None)


def load_to_mysql(df, engine):
    sql = text(f"""
        INSERT INTO {TABLE} (company_name, permit_count, sector, size_of_company)
        VALUES (:company_name, :permit_count, :sector, :size_of_company)
        ON DUPLICATE KEY UPDATE
            permit_count = VALUES(permit_count),
            sector = VALUES(sector),
            size_of_company = VALUES(size_of_company)
    """)
    records = df.to_dict(orient="records")
    with engine.begin() as conn:
        conn.execute(sql, records)
    print(f"Loaded {len(records)} rows into {TABLE}")


def verify(engine):
    with engine.connect() as conn:
        total = conn.execute(text(f"SELECT COUNT(*) FROM {TABLE}")).scalar()
        permits = conn.execute(text(f"SELECT COALESCE(SUM(permit_count), 0) FROM {TABLE}")).scalar()
        print(f"Table now has {total} companies, {permits} total permits")
        rows = conn.execute(
            text(f"SELECT id, company_name, permit_count, sector, size_of_company FROM {TABLE} LIMIT 5")
        ).fetchall()
        for r in rows:
            print(r)


if __name__ == "__main__":
    engine = get_engine()
    data = load_and_clean(CSV_PATH)
    load_to_mysql(data, engine)
    verify(engine)